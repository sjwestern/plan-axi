import { existsSync } from "node:fs";
import { join } from "node:path";
import { applyEol, detectEol, normalizeEol, readText, writeText } from "./fsutil.js";
import { OTHER, SECTIONS, SECTION_GUIDE, displayTitle, type Ctx, type Doc, type DocSection } from "./model.js";

export const INDEX_START = "<!-- docs-axi:index:start - generated by `docs-axi index`, do not edit -->";
export const INDEX_END = "<!-- docs-axi:index:end -->";
const START_RE = /<!-- docs-axi:index:start[^>]*-->/;
const END_RE = /<!-- docs-axi:index:end\s*-->/;

const HEADINGS: Record<DocSection, string> = {
  domain: "Domain",
  architecture: "Architecture",
  decisions: "Decisions",
  other: "Other",
};

function escapeLinkText(s: string): string {
  return s.replace(/[[\]]/g, (c) => `\\${c}`);
}

function entry(d: Doc): string {
  let title = displayTitle(d);
  if (d.adrNumber !== undefined) {
    title = `${String(d.adrNumber).padStart(4, "0")} ${title}`;
  }
  const summary = d.summary ?? "(no summary)";
  const status = d.section === "decisions" && d.status ? ` (${d.status})` : "";
  return `- [${escapeLinkText(title)}](${d.path}) - ${summary}${status}`;
}

/** The generated block (LF endings, no trailing newline). */
export function renderIndexBlock(docs: Doc[]): string {
  const out: string[] = [INDEX_START];
  for (const section of SECTIONS) {
    out.push("", `## ${HEADINGS[section]}`, "");
    const inSection = docs.filter((d) => d.section === section);
    if (inSection.length === 0) out.push("_No docs yet._");
    else for (const d of inSection) out.push(entry(d));
  }
  const other = docs.filter((d) => d.section === OTHER);
  if (other.length > 0) {
    out.push("", `## ${HEADINGS[OTHER]}`, "", "_Outside the standard layout; indexed in place._", "");
    for (const d of other) out.push(entry(d));
  }
  out.push(INDEX_END);
  return out.join("\n");
}

export const README_INTRO = `# Docs

Shared reference for humans and agents. Read this index first and open only what you need.

${SECTIONS.map((s) => "- `" + s + "/` - " + SECTION_GUIDE[s]).join("\n")}

Manage with \`docs-axi\` (search, new, update, check). Keep files small and single-topic; link instead of repeating.

`;

function readmePath(ctx: Ctx): string {
  return join(ctx.docsDir, "README.md");
}

/** Expected README text (LF) given current text (LF) or undefined if missing. */
export function expectedReadme(current: string | undefined, docs: Doc[]): string {
  const block = renderIndexBlock(docs);
  if (current === undefined) return `${README_INTRO}${block}\n`;
  const s = START_RE.exec(current);
  const e = END_RE.exec(current);
  if (s && e && e.index > s.index) {
    return current.slice(0, s.index) + block + current.slice(e.index + e[0].length);
  }
  const sep = current.endsWith("\n") ? "\n" : "\n\n";
  return `${current}${sep}${block}\n`;
}

export function readmeState(
  ctx: Ctx,
  docs: Doc[],
): { path: string; expected: string; actual: string | undefined; eol: "\n" | "\r\n" } {
  const path = readmePath(ctx);
  const raw = existsSync(path) ? readText(path) : undefined;
  const actual = raw === undefined ? undefined : normalizeEol(raw);
  return {
    path,
    expected: expectedReadme(actual, docs),
    actual,
    eol: raw === undefined ? "\n" : detectEol(raw),
  };
}

/** Regenerate the index. Returns true when the file changed. */
export function writeIndex(ctx: Ctx, docs: Doc[]): boolean {
  const st = readmeState(ctx, docs);
  if (st.actual === st.expected) return false;
  writeText(st.path, applyEol(st.expected, st.eol));
  return true;
}
